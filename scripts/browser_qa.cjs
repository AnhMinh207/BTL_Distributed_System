/* Optional browser QA. Install Playwright in runtime/browser-qa; use installed Edge. */
const {chromium}=require('../runtime/browser-qa/node_modules/playwright');
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');

(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_PATH||'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
  const context=await browser.newContext({viewport:{width:1440,height:1100},locale:'vi-VN'});
  const page=await context.newPage();const errors=[];const checks=[];
  const appUrl=process.env.APP_URL||'http://127.0.0.1:8080';
  page.on('pageerror',e=>errors.push(e.message));
  try{
    await page.goto(appUrl,{waitUntil:'networkidle'});
    await page.getByRole('heading',{name:'Đi đâu hôm nay?'}).waitFor();
    assert.equal(await page.locator('#auth-panel').isVisible(),true);
    checks.push('Guest auth and booking screen renders');
    await page.locator('#demo-setup').click();
    await page.locator('[data-role="driver"]').waitFor();
    await page.waitForFunction(()=>document.querySelector('#demo-setup').disabled===false);
    checks.push('Demo registers two real accounts and makes driver available');
    await page.locator('#book-button').click();
    await page.waitForFunction(()=>document.querySelector('#trip-badge').textContent==='Chờ tài xế nhận',{},{timeout:30000});
    await page.screenshot({path:'docs/ui-passenger.png',fullPage:true});
    checks.push('Passenger booking reaches offered through real matching');
    await page.locator('[data-role="driver"]').click();
    await page.locator('[data-action="accept"]').waitFor();
    await page.screenshot({path:'docs/ui-driver.png',fullPage:true});
    await page.locator('[data-action="accept"]').click();
    await page.locator('[data-action="start"]').click();
    await page.locator('[data-action="complete"]').click();
    await page.waitForFunction(()=>document.querySelector('#trip-badge').textContent==='Đã hoàn tất',{},{timeout:30000});
    checks.push('Driver accepts, starts and completes; payment settles');
    await page.locator('[data-role="passenger"]').click();
    await page.locator('.nav-item[data-view="payments"]').click();
    await page.getByRole('cell',{name:'Thành công',exact:true}).waitFor();
    await page.locator('.nav-item[data-view="notifications"]').click();
    await page.getByText('Thanh toán thành công',{exact:true}).waitFor();
    checks.push('Passenger payment ledger and notifications display real results');
    await page.locator('.nav-item[data-view="ride"]').click();
    await page.locator('#demo-run').click();
    await page.waitForFunction(()=>document.querySelector('#demo-badge').textContent==='Đã hoàn tất',{},{timeout:45000});
    checks.push('Visible automatic demo finishes all seven steps');
    await page.reload({waitUntil:'networkidle'});
    await page.locator('[data-role="driver"]').waitFor();
    checks.push('Session survives reload inside the same browser tab');
    await page.locator('[data-add-account]').click();
    await page.waitForTimeout(2500);
    assert.equal(await page.locator('#auth-panel').isVisible(),true);
    checks.push('Add-account form remains open while polling');
    const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1});
    const mobilePage=await mobile.newPage();mobilePage.on('pageerror',e=>errors.push(e.message));
    await mobilePage.goto(appUrl,{waitUntil:'networkidle'});
    assert.equal(await mobilePage.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
    await mobilePage.screenshot({path:'docs/ui-mobile.png',fullPage:true});
    checks.push('Mobile 390px layout has no horizontal overflow');
    const name='webui_'+Date.now().toString(36),password='Browser-check-'+Date.now()+'!';
    await mobilePage.locator('[data-auth="register"]').click();
    await mobilePage.locator('#username').fill(name);await mobilePage.locator('#password').fill(password);
    await mobilePage.locator('#auth-submit').click();
    await mobilePage.waitForFunction(()=>document.querySelector('#auth-panel').hidden);
    await mobilePage.locator('#logout').click();
    await mobilePage.locator('[data-auth="login"]').click();
    await mobilePage.locator('#username').fill(name);await mobilePage.locator('#password').fill(password);
    await mobilePage.locator('#auth-submit').click();
    await mobilePage.waitForFunction(()=>document.querySelector('#auth-panel').hidden);
    checks.push('Manual registration, logout and login work on mobile');
    mobilePage.on('dialog',dialog=>dialog.accept());
    await mobilePage.locator('#demo-setup').click();
    await mobilePage.locator('[data-role="driver"]').waitFor();
    await mobilePage.waitForFunction(()=>!document.querySelector('#demo-setup').disabled);
    await mobilePage.locator('#book-button').click();
    await mobilePage.waitForFunction(()=>document.querySelector('#trip-badge').textContent==='Chờ tài xế nhận',{},{timeout:30000});
    await mobilePage.locator('[data-action="cancel"]').click();
    await mobilePage.waitForFunction(()=>document.querySelector('#trip-badge').textContent==='Đã hủy');
    await mobilePage.locator('[data-role="driver"]').click();
    await mobilePage.waitForFunction(()=>document.querySelector('#driver-status-label').textContent==='Đang nhận chuyến');
    checks.push('Passenger cancellation releases the driver');
    await mobilePage.locator('[data-role="passenger"]').click();
    await mobilePage.locator('#book-button').click();
    await mobilePage.waitForFunction(()=>document.querySelector('#trip-badge').textContent==='Chờ tài xế nhận',{},{timeout:30000});
    await mobilePage.locator('[data-role="driver"]').click();
    await mobilePage.locator('[data-action="reject"]').click();
    await mobilePage.waitForFunction(()=>document.querySelector('#trip-badge').textContent==='Đã hủy');
    checks.push('Driver rejection cancels the trip');
    await mobilePage.locator('[data-role="passenger"]').click();
    await mobilePage.locator('#payment-mode').selectOption('decline');
    await mobilePage.locator('#book-button').click();
    await mobilePage.waitForFunction(()=>document.querySelector('#trip-badge').textContent==='Chờ tài xế nhận',{},{timeout:30000});
    await mobilePage.locator('[data-role="driver"]').click();
    for(const action of ['accept','start','complete'])await mobilePage.locator(`[data-action="${action}"]`).click();
    await mobilePage.waitForFunction(()=>document.querySelector('#trip-badge').textContent==='Thanh toán thất bại',{},{timeout:30000});
    await mobilePage.waitForFunction(()=>document.querySelector('#driver-status-label').textContent==='Đang nhận chuyến');
    checks.push('Declined payment is visible and Saga releases the driver');
    await mobile.close();
    assert.deepEqual(errors,[]);
    checks.push('No uncaught browser JavaScript errors');
    fs.writeFileSync('docs/browser-results.json',JSON.stringify({passed:checks.length,checks,errors,browser:'Installed Microsoft Edge; Playwright',viewport:'1440x1100 and 390x844'},null,2));
    console.log(JSON.stringify({passed:checks.length,checks},null,2));
  }catch(e){
    await page.screenshot({path:'runtime/browser-failure.png',fullPage:true}).catch(()=>{});
    fs.writeFileSync('runtime/browser-failure.json',JSON.stringify({message:e.message,checks,errors},null,2));
    throw e;
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
